
from flask import (
    Flask, render_template, request, redirect,
    url_for, session, render_template_string
)
import os
import sqlite3
import secrets
import hmac

app = Flask(__name__)

app.secret_key = os.environ.get("SECRET_KEY")

app.config.update(
    SESSION_COOKIE_HTTPONLY=True,
    SESSION_COOKIE_SAMESITE="Lax",
    SESSION_COOKIE_SECURE=True,
)

DATABASE_URL = os.environ.get("DATABASE_URL")
DATABASE = os.environ.get("DATABASE_PATH", "barberbook.db")

if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row


def get_db_connection():
    if DATABASE_URL:
        return psycopg.connect(DATABASE_URL, row_factory=dict_row)

    conn = sqlite3.connect(DATABASE)
    conn.row_factory = sqlite3.Row
    return conn


def init_db():
    conn = get_db_connection()

    try:
        if DATABASE_URL:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS appointments (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name TEXT NOT NULL,
                    email TEXT NOT NULL,
                    service TEXT NOT NULL,
                    barber TEXT NOT NULL,
                    date TEXT NOT NULL,
                    time TEXT NOT NULL
                )
                """
            )
        else:
            conn.execute(
                """
                CREATE TABLE IF NOT EXISTS appointments (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    name TEXT NOT NULL,
                    email TEXT NOT NULL,
                    service TEXT NOT NULL,
                    barber TEXT NOT NULL,
                    date TEXT NOT NULL,
                    time TEXT NOT NULL
                )
                """
            )

        conn.commit()
    finally:
        conn.close()


init_db()


@app.route("/")
def home():
    return render_template("index.html")


@app.route("/book", methods=["GET", "POST"])
def book():
    if request.method == "POST":
        name = request.form.get("name", "").strip()
        email = request.form.get("email", "").strip()
        service = request.form.get("service", "").strip()
        barber = request.form.get("barber", "").strip()
        date = request.form.get("date", "").strip()
        time = request.form.get("time", "").strip()

        if not all([name, email, service, barber, date, time]):
            return render_template(
                "booking.html",
                error="Please complete all fields."
            ), 400

        conn = get_db_connection()

        try:
            placeholder = "%s" if DATABASE_URL else "?"
            conn.execute(
                f"""
                INSERT INTO appointments
                (name, email, service, barber, date, time)
                VALUES ({placeholder}, {placeholder}, {placeholder},
                        {placeholder}, {placeholder}, {placeholder})
                """,
                (name, email, service, barber, date, time)
            )
            conn.commit()
        finally:
            conn.close()

        return render_template(
            "confirmation.html",
            name=name,
            service=service,
            barber=barber,
            date=date,
            time=time
        )

    return render_template("booking.html")


@app.route("/admin")
def admin():
    conn = get_db_connection()

    try:
        appointments = conn.execute(
            """
            SELECT *
            FROM appointments
            ORDER BY date, time
            """
        ).fetchall()
    finally:
        conn.close()

    return render_template(
        "admin.html",
        appointments=appointments
    )


if __name__ == "__main__":
    app.run(host="0.0.0.0", port=int(os.environ.get("PORT", 5000)))
